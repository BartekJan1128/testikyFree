-- ---------- Tabulky ----------------------------------------------------

create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  email        text not null,
  display_name text,
  is_admin     boolean not null default false,
  created_at   timestamptz not null default now()
);

create table if not exists public.tests (
  id                bigint generated by default as identity primary key,
  title             text not null,
  description       text not null default '',
  shuffle_questions boolean not null default false,
  shuffle_answers   boolean not null default false,
  is_published      boolean not null default true,
  created_at        timestamptz not null default now()
);

create table if not exists public.questions (
  id          bigint generated by default as identity primary key,
  test_id     bigint not null references public.tests(id) on delete cascade,
  text        text not null,
  explanation text not null default '',
  position    int not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists questions_test_idx on public.questions(test_id, position);

create table if not exists public.answers (
  id          bigint generated by default as identity primary key,
  question_id bigint not null references public.questions(id) on delete cascade,
  text        text not null,
  is_correct  boolean not null default false,
  position    int not null default 0
);
create index if not exists answers_question_idx on public.answers(question_id, position);

create table if not exists public.test_access (
  test_id    bigint not null references public.tests(id) on delete cascade,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  granted_at timestamptz not null default now(),
  primary key (test_id, user_id)
);

create table if not exists public.attempts (
  id            bigint generated by default as identity primary key,
  test_id       bigint references public.tests(id) on delete set null,
  test_title    text not null,
  user_id       uuid not null references public.profiles(id) on delete cascade,
  started_at    timestamptz,
  finished_at   timestamptz not null default now(),
  correct_count int not null,
  total_count   int not null,
  score_pct     numeric(5,2) not null
);
create index if not exists attempts_user_idx on public.attempts(user_id, finished_at desc);
create index if not exists attempts_test_idx on public.attempts(test_id);

-- Snapshot otázky v okamžiku odevzdání -> historie se nerozbije, když admin otázku upraví/smaže
create table if not exists public.attempt_answers (
  id                  bigint generated by default as identity primary key,
  attempt_id          bigint not null references public.attempts(id) on delete cascade,
  question_id         bigint not null,           -- původní ID otázky (pro vyhledávání)
  question_text       text not null,
  explanation         text not null default '',
  answers             jsonb not null,            -- [{id, text, is_correct}]
  selected_answer_ids bigint[] not null default '{}',
  is_correct          boolean not null,
  position            int not null
);
create index if not exists attempt_answers_attempt_idx on public.attempt_answers(attempt_id, position);

-- ---------- Migrace: otázky typu „přiřazování“ --------------------------
--   choice = výběr odpovědí (výchozí), match = přiřazování dvojic
--   u match: answers.text = levá položka, answers.match_text = správná možnost;
--            řádek s prázdným text = matoucí možnost navíc (distraktor)
alter table public.questions add column if not exists type text not null default 'choice';
alter table public.questions drop constraint if exists questions_type_check;
alter table public.questions add constraint questions_type_check check (type in ('choice', 'match'));
alter table public.answers add column if not exists match_text text;
alter table public.attempt_answers add column if not exists question_type text not null default 'choice';
alter table public.attempt_answers add column if not exists selected_matches jsonb;

-- ---------- Pomocné funkce ---------------------------------------------

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

create or replace function public.has_test_access(p_test_id bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from public.test_access a
    join public.tests t on t.id = a.test_id
    where a.test_id = p_test_id and a.user_id = auth.uid() and t.is_published
  );
$$;

-- Profil se vytvoří automaticky při registraci.
-- Úplně první registrovaný uživatel se stane adminem.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, display_name, is_admin)
  values (
    new.id,
    new.email,
    coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(new.email, '@', 1)),
    not exists (select 1 from public.profiles)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

