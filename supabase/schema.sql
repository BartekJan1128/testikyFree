-- Přehled testů dostupných přihlášenému uživateli (+ jeho statistiky)
create or replace function public.list_my_tests()
returns table (id bigint, title text, description text, question_count bigint, best_pct numeric, attempts_count bigint, last_at timestamptz)
language sql stable security definer set search_path = public as $$
  select t.id, t.title, t.description,
    (select count(*) from questions q where q.test_id = t.id),
    (select max(a.score_pct) from attempts a where a.test_id = t.id and a.user_id = auth.uid()),
    (select count(*) from attempts a where a.test_id = t.id and a.user_id = auth.uid()),
    (select max(a.finished_at) from attempts a where a.test_id = t.id and a.user_id = auth.uid())
  from tests t
  where auth.uid() is not null and public.has_test_access(t.id)
  order by t.created_at desc;
$$;

-- Admin může povýšit / odebrat admina jinému uživateli
create or replace function public.set_user_admin(p_user_id uuid, p_is_admin boolean)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Pouze pro admina.'; end if;
  if p_user_id = auth.uid() and not p_is_admin then raise exception 'Nemůžeš odebrat admina sám sobě.'; end if;
  update profiles set is_admin = p_is_admin where id = p_user_id;
end;
$$;

revoke execute on function public.list_my_tests() from anon, public;
revoke execute on function public.set_user_admin(uuid, boolean) from anon, public;
grant execute on function public.list_my_tests() to authenticated;
grant execute on function public.set_user_admin(uuid, boolean) to authenticated;

